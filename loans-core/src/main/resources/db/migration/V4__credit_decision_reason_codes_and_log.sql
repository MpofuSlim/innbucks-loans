-- Credit decisions carry a reason code and a comment, a loan can be returned for more information,
-- and every credit action is kept in an append-only log with the data it was based on
-- (FR-SSB-015, applying FR-PBL-027, FR-PBL-029 and FR-PBL-032).

-- The reason codes a credit officer picks from. A code belongs to exactly one decision; an inactive
-- code stays for the history that names it but can no longer be chosen.
CREATE TABLE credit_reason_codes (
    code          VARCHAR(64)  NOT NULL,
    decision      VARCHAR(32)  NOT NULL,
    description   VARCHAR(255) NOT NULL,
    active        BOOLEAN      NOT NULL,
    display_order INTEGER      NOT NULL,
    CONSTRAINT credit_reason_codes_pkey PRIMARY KEY (code),
    CONSTRAINT ck_credit_reason_codes_decision CHECK (decision IN ('APPROVED', 'REJECTED', 'RETURNED'))
);

