-- The public loan reference (LN-2026-00042). Drawn by the saga when a loan is
-- disbursed; the internal zero-padded reference Ndasenda uses is separate.
CREATE SEQUENCE loan_public_ref_seq START WITH 1;
CREATE UNIQUE INDEX uq_loans_public_reference ON loans (public_reference) WHERE public_reference IS NOT NULL;

-- The pending-application check matches an applicant by EC number or national ID
-- compared upper-cased, which the plain index on ec_number cannot serve.
CREATE INDEX idx_loans_upper_ec_number ON loans (upper(ec_number));
CREATE INDEX idx_loans_upper_national_id_number ON loans (upper(national_id_number));

-- The ledger is append-only: a correction is a reversing entry, never an edit.
CREATE FUNCTION ledger_entries_immutable() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'ledger_entries is append-only: % is forbidden. Post a reversing entry instead.', TG_OP;
END;
$$ LANGUAGE PLPGSQL;

CREATE TRIGGER trg_ledger_entries_immutable
    BEFORE UPDATE OR DELETE ON ledger_entries
    FOR EACH ROW EXECUTE FUNCTION ledger_entries_immutable();
