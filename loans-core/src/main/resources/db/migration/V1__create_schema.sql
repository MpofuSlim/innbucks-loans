-- ============================================================================
-- The loans schema, created on an empty database.
--
-- Naming: tables are plural snake_case, columns snake_case. Constraints are
-- <table>_pkey, fk_<table>_<column>, uq_<table>_<columns> and ck_<table>_<column>;
-- indexes are idx_<table>_<columns>. A database Hibernate built before Flyway
-- (ddl-auto: update) is baselined at this version and upgraded by V2 instead.
--
-- Timestamps are UTC (the containers pin -Duser.timezone=UTC and the code writes
-- LocalDateTime.now(ZoneOffset.UTC)); money is numeric in major units.
-- ============================================================================

