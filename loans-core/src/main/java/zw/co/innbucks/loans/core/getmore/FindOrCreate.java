package zw.co.innbucks.loans.core.getmore;

import java.util.List;

/**
 * What {@link GetMoreCoupons#findOrCreate} ended with: a coupon bound to the voucher's value, or a state only an
 * operator can resolve. A store that could not answer is not an outcome here: it is thrown
 * ({@link GetMoreUnavailableException}, {@link GetMoreOutcomeUnknownException}, {@link GetMoreRejectedException}).
 */
public sealed interface FindOrCreate {

    /** More coupons on the prefix than three pages: not loans' alone. */
    String TOO_MANY_ON_PREFIX = "TOO_MANY_ON_PREFIX";
    /** The generate allowance is used up and its coupon never showed up on the prefix. */
    String GENERATED_NOT_FOUND = "GENERATED_NOT_FOUND";
    /** The store generated a code without the prefix or length asked for; it was withdrawn at once. */
    String PREFIX_NOT_HONOURED = "PREFIX_NOT_HONOURED";
    /** A coupon on the prefix under another rule, or created before the first claim: not made by loans. */
    String FOREIGN_COUPON = "FOREIGN_COUPON";
    /** Several coupons on the prefix, more than one already used. */
    String DUPLICATE_COUPONS_USED = "DUPLICATE_COUPONS_USED";
    /** The coupon found was already used before loans bound it: someone else had the code. */
    String COUPON_ALREADY_USED = "COUPON_ALREADY_USED";

    /**
     * The voucher's coupon, worth its face value.
     *
     * @param adopted               found on the prefix rather than generated by this call
     * @param extrasWithdrawnMasked other unused coupons on the prefix, withdrawn, as {@code ****8B1C}
     */
    record Bound(GetMoreCoupon coupon, boolean adopted, List<String> extrasWithdrawnMasked) implements FindOrCreate {

        public Bound {
            extrasWithdrawnMasked = extrasWithdrawnMasked == null ? List.of() : List.copyOf(extrasWithdrawnMasked);
        }
    }

    /**
     * Stopped for an operator.
     *
     * @param outcome         one of the constants above
     * @param detail          masked text for the operator
     * @param liveOrphanCodes full codes the store returned that could not be confirmed withdrawn; never log them
     */
    record Parked(String outcome, String detail, List<String> liveOrphanCodes) implements FindOrCreate {

        public Parked {
            liveOrphanCodes = liveOrphanCodes == null ? List.of() : List.copyOf(liveOrphanCodes);
        }

        /** The orphan codes only as {@code ****8B1C}. */
        @Override
        public String toString() {
            return "Parked[outcome=" + outcome + ", detail=" + detail + ", liveOrphanCodes="
                    + liveOrphanCodes.stream().map(GetMoreCodes::maskedCode).toList() + "]";
        }
    }
}
